using System.Text;

namespace Loscardos.TikTokPartnerSdk.Generator;

public sealed class ContractsWriter
{
    public string WriteModule(string moduleName, string moduleKey, IReadOnlyList<SchemaEndpoint> endpoints)
    {
        var builder = new StringBuilder();
        var modulePascal = TikTokName.ToPascalCase(moduleKey);

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System.Text.Json.Serialization;");
        builder.AppendLine($"namespace Loscardos.TikTokPartnerSdk.Generated.{modulePascal};");
        builder.AppendLine();

        foreach (var endpoint in endpoints)
        {
            var requestTypeName = TikTokName.ToRequestTypeName(endpoint);
            var responseTypeName = TikTokName.ToResponseTypeName(endpoint);

            WriteRecord(
                builder,
                requestTypeName,
                endpoint.RequestParameters,
                omitOptionalDefaults: true);
            builder.AppendLine();
            WriteNestedTypes(
                builder,
                requestTypeName,
                endpoint.RequestParameters,
                omitOptionalDefaults: true);
            builder.AppendLine();
            WriteRecord(
                builder,
                responseTypeName,
                endpoint.ResponseParameters,
                omitOptionalDefaults: false);
            builder.AppendLine();
            WriteNestedTypes(
                builder,
                responseTypeName,
                endpoint.ResponseParameters,
                omitOptionalDefaults: false);
            builder.AppendLine();
        }

        return builder.ToString().TrimEnd() + Environment.NewLine;
    }

    private static void WriteRecord(
        StringBuilder builder,
        string typeName,
        IReadOnlyList<SchemaParameter> parameters,
        bool omitOptionalDefaults)
    {
        if (parameters.Count == 0)
        {
            builder.AppendLine($"public sealed record {typeName}();");
            return;
        }

        builder.AppendLine($"public sealed record {typeName}(");

        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            var suffix = index == parameters.Count - 1 ? ");" : ",";
            if (omitOptionalDefaults && !parameter.Required)
            {
                builder.AppendLine(
                    "    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]");
            }
            builder.AppendLine(
                $"    [property: JsonPropertyName(\"{parameter.Name}\")] {MapContractType(parameter, typeName, omitOptionalDefaults)} {TikTokName.ToPropertyName(parameter, parameters)}{suffix}");
        }
    }

    private static void WriteNestedTypes(
        StringBuilder builder,
        string parentTypeName,
        IReadOnlyList<SchemaParameter> parameters,
        bool omitOptionalDefaults)
    {
        foreach (var parameter in parameters.Where(static x => x.Children.Count > 0))
        {
            var childTypeName = TikTokName.ToChildTypeName(parentTypeName, parameter.Name);
            WriteRecord(
                builder,
                childTypeName,
                parameter.Children,
                omitOptionalDefaults);
            builder.AppendLine();
            WriteNestedTypes(
                builder,
                childTypeName,
                parameter.Children,
                omitOptionalDefaults);
        }
    }

    private static string MapContractType(
        SchemaParameter parameter,
        string parentTypeName,
        bool requestContract)
    {
        var type = TikTokTypeMapper.MapType(parameter, parentTypeName);
        return requestContract && !parameter.Required && IsValueType(type)
            ? type + "?"
            : type;
    }

    private static bool IsValueType(string type)
        => type is "long" or "bool" or "decimal";
}
