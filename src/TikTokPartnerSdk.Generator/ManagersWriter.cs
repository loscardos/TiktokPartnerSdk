using System.Text;

namespace TikTokPartnerSdk.Generator;

public sealed class ManagersWriter
{
    private static readonly HashSet<string> ReservedQueryParameters = new(StringComparer.Ordinal)
    {
        "app_key",
        "timestamp",
        "sign"
    };

    public string WriteInterface(string moduleName, string moduleKey, IReadOnlyList<SchemaEndpoint> endpoints)
    {
        var builder = new StringBuilder();
        var modulePascal = TikTokName.ToPascalCase(moduleKey);
        var interfaceName = TikTokName.ToManagerInterfaceName(moduleKey);

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine($"using TikTokPartnerSdk.Generated.{modulePascal};");
        builder.AppendLine();
        builder.AppendLine("namespace TikTokPartnerSdk.Abstractions.Managers.Generated;");
        builder.AppendLine();
        builder.AppendLine($"public interface {interfaceName}");
        builder.AppendLine("{");

        foreach (var endpoint in endpoints)
        {
            builder.AppendLine("    /// <summary>");
            builder.AppendLine($"    /// Access token kind: {endpoint.AccessTokenKind}");
            builder.AppendLine($"    /// Required headers: {string.Join(", ", endpoint.RequiredHeaders)}");
            builder.AppendLine("    /// </summary>");
            builder.AppendLine($"    Task<{TikTokName.ToResponseTypeName(endpoint)}> {TikTokName.ToManagerMethodName(endpoint)}Async(");
            builder.AppendLine("        string accessToken,");
            builder.AppendLine($"        {TikTokName.ToRequestTypeName(endpoint)} request,");
            builder.AppendLine("        CancellationToken cancellationToken);");
        }

        builder.AppendLine("}");
        return builder.ToString().TrimEnd() + Environment.NewLine;
    }

    public string WriteImplementation(string moduleName, string moduleKey, IReadOnlyList<SchemaEndpoint> endpoints)
    {
        var builder = new StringBuilder();
        var modulePascal = TikTokName.ToPascalCase(moduleKey);
        var implementationName = TikTokName.ToManagerImplementationName(moduleKey);
        var interfaceName = TikTokName.ToManagerInterfaceName(moduleKey);

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using TikTokPartnerSdk.Abstractions.Http;");
        builder.AppendLine("using TikTokPartnerSdk.Abstractions.Managers.Generated;");
        builder.AppendLine($"using TikTokPartnerSdk.Generated.{modulePascal};");
        builder.AppendLine();
        builder.AppendLine("namespace TikTokPartnerSdk.Core.Managers.Generated;");
        builder.AppendLine();
        builder.AppendLine($"public sealed class {implementationName}(ITikTokPartnerClient client) : {interfaceName}");
        builder.AppendLine("{");

        foreach (var endpoint in endpoints)
        {
            builder.AppendLine($"    public async Task<{TikTokName.ToResponseTypeName(endpoint)}> {TikTokName.ToManagerMethodName(endpoint)}Async(");
            builder.AppendLine("        string accessToken,");
            builder.AppendLine($"        {TikTokName.ToRequestTypeName(endpoint)} request,");
            builder.AppendLine("        CancellationToken cancellationToken)");
            builder.AppendLine("    {");
            builder.AppendLine("        // Generated from schema metadata:");
            builder.AppendLine($"        // access_token_kind={endpoint.AccessTokenKind}");
            builder.AppendLine($"        // required_headers={string.Join(",", endpoint.RequiredHeaders)}");
            builder.AppendLine("        var query = new Dictionary<string, object?>();");

            foreach (var parameter in endpoint.RequestParameters.Where(static parameter => parameter.Location == "query"))
            {
                if (ReservedQueryParameters.Contains(parameter.Name))
                {
                    continue;
                }

                builder.AppendLine($"        query[\"{parameter.Name}\"] = request.{TikTokName.ToPascalCase(parameter.Name)};");
            }

            var bodyParameters = endpoint.RequestParameters
                .Where(static parameter => parameter.Location == "body")
                .ToArray();
            if (bodyParameters.Length > 0)
            {
                builder.AppendLine("        var body = new Dictionary<string, object?>();");
                foreach (var parameter in bodyParameters)
                {
                    builder.AppendLine($"        body[\"{parameter.Name}\"] = request.{TikTokName.ToPascalCase(parameter.Name)};");
                }
            }

            builder.AppendLine($"        var path = \"{endpoint.Path}\";");
            foreach (var parameter in PathParameters(endpoint))
            {
                builder.AppendLine($"        path = path.Replace(\"{{{parameter.Name}}}\", Uri.EscapeDataString(Convert.ToString(request.{TikTokName.ToPascalCase(parameter.Name)}, System.Globalization.CultureInfo.InvariantCulture) ?? string.Empty));");
            }

            builder.AppendLine($"        var envelope = await client.SendAsync<{ToEnvelopePayloadType(endpoint)}>(");
            builder.AppendLine("            new TikTokPartnerRequest(");
            builder.AppendLine($"                HttpMethod.{ToHttpMethod(endpoint.HttpMethod)},");
            builder.AppendLine("                path,");
            builder.AppendLine("                query,");
            builder.AppendLine($"                {ToBodyExpression(endpoint, bodyParameters.Length > 0)},");
            builder.AppendLine("                null,");
            builder.AppendLine("                accessToken),");
            builder.AppendLine("            cancellationToken);");
            builder.AppendLine($"        return new {TikTokName.ToResponseTypeName(endpoint)}(");
            builder.AppendLine("            envelope.Code,");
            builder.AppendLine("            envelope.Message,");
            builder.AppendLine($"            {ToRequestIdExpression(endpoint)}{ToAdditionalResponseArguments(endpoint)});");
            builder.AppendLine("    }");
            builder.AppendLine();
        }

        builder.AppendLine("}");
        return builder.ToString().TrimEnd() + Environment.NewLine;
    }

    private static string ToHttpMethod(string httpMethod)
        => httpMethod.ToUpperInvariant() switch
        {
            "GET" => "Get",
            "POST" => "Post",
            "PUT" => "Put",
            "DELETE" => "Delete",
            "PATCH" => "Patch",
            _ => throw new InvalidOperationException($"Unsupported HTTP method '{httpMethod}'.")
        };

    private static string ToBodyExpression(SchemaEndpoint endpoint, bool hasBodyParameters)
        => endpoint.RequestContentKind.Equals("body", StringComparison.OrdinalIgnoreCase) && hasBodyParameters
            ? "body"
            : "null";

    private static string ToEnvelopePayloadType(SchemaEndpoint endpoint)
    {
        var dataParameter = endpoint.ResponseParameters.FirstOrDefault(parameter => parameter.Name.Equals("data", StringComparison.Ordinal));
        if (dataParameter is null)
        {
            return "object";
        }

        return dataParameter.Children.Count > 0
            ? TikTokName.ToResponseTypeName(endpoint) + "Data"
            : TikTokTypeMapper.MapType(dataParameter, TikTokName.ToResponseTypeName(endpoint));
    }

    private static string ToRequestIdExpression(SchemaEndpoint endpoint)
        => HasResponseParameter(endpoint, "request_id")
            ? "envelope.RequestId ?? string.Empty"
            : "null";

    private static string ToAdditionalResponseArguments(SchemaEndpoint endpoint)
        => HasResponseParameter(endpoint, "data")
            ? "," + Environment.NewLine + "            envelope.Data ?? throw new InvalidOperationException(\"TikTok API response data was missing.\")"
            : string.Empty;

    private static bool HasResponseParameter(SchemaEndpoint endpoint, string name)
        => endpoint.ResponseParameters.Any(parameter => parameter.Name.Equals(name, StringComparison.Ordinal));

    private static IEnumerable<SchemaParameter> PathParameters(SchemaEndpoint endpoint)
        => endpoint.RequestParameters.Where(static parameter => parameter.Location == "path");
}
